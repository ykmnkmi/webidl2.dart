/// Token types for WebIDL.
enum TokenType {
  // Keywords
  interfaceKeyword,
  partialKeyword,
  dictionaryKeyword,
  enumKeyword,
  callbackKeyword,
  typeDefKeyword,
  implementsKeyword,
  constKeyword,
  nullKeyword,
  trueKeyword,
  falseKeyword,
  staticKeyword,
  stringifierKeyword,
  attributeKeyword,
  readOnlyKeyword,
  inheritKeyword,
  getterKeyword,
  setterKeyword,
  deleterKeyword,
  requiredKeyword,
  optionalKeyword,

  // Types
  unsignedType,
  shortType,
  longType,
  floatType,
  doubleType,
  booleanType,
  byteType,
  octetType,
  voidType,
  anyType,
  objectType,
  symbolType,
  promiseType,
  sequenceType,
  recordType,

  // Special tokens
  identifier,
  integer,
  float,
  string,

  // Punctuation
  leftBrace,
  rightBrace,
  leftParen,
  rightParen,
  leftBracket,
  rightBracket,
  semiColon,
  colon,
  comma,
  question,
  equals,
  lessThan,
  greaterThan,
  ellipsis,
  or,

  // Other
  comment,
  documentComment,
  whiteSpace,
  eof,
  error,
}
